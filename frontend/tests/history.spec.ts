import { test, expect } from '@playwright/test';
import { join } from 'node:path';

test('saved private history shows fills and cancellations; database failure can retry without blocking trading', async ({ browser }) => {
  const a=await browser.newContext(),b=await browser.newContext();
  const seller=await a.newPage(),buyer=await b.newPage();
  await Promise.all([seller.goto('/trade'),buyer.goto('/trade')]);
  await expect(seller.getByText('Live connection',{exact:true})).toBeVisible();
  await expect(buyer.getByText('Live connection',{exact:true})).toBeVisible();
  await seller.getByRole('button',{name:'Sell',exact:true}).click();
  await seller.getByLabel('Limit price').fill('9');await seller.getByLabel('Amount').fill('3');
  await seller.getByRole('button',{name:'Sell SOL',exact:true}).click();
  await expect(seller.getByRole('button',{name:'Cancel',exact:true})).toHaveCount(1);
  await buyer.getByLabel('Limit price').fill('10');await buyer.getByLabel('Amount').fill('1');
  await buyer.getByRole('button',{name:'Buy SOL',exact:true}).click();
  await expect(seller.locator('tbody tr')).toContainText('1.0000');
  await seller.getByRole('button',{name:'Cancel',exact:true}).click();
  await expect(seller.getByRole('button',{name:'Cancel',exact:true})).toHaveCount(0);
  let unavailable=true;
  await seller.route('**/api/v1/order/history?*',route=>unavailable ? route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({success:false,message:'Temporarily unavailable'})}) : route.continue());
  await seller.getByRole('tab',{name:'History',exact:true}).click();
  await expect(seller.getByText('History is unavailable.',{exact:false})).toBeVisible();
  await expect(seller.getByRole('button',{name:'Sell SOL',exact:true})).toBeEnabled();
  unavailable=false;await seller.getByRole('button',{name:'Refresh history'}).click();
  await expect(seller.getByRole('table',{name:'Order history'}).locator('tbody tr')).toHaveCount(1);
  await expect(seller.getByRole('table',{name:'Order history'})).toContainText('cancelled');
  await buyer.getByRole('tab',{name:'History',exact:true}).click();
  await expect(buyer.getByRole('table',{name:'Order history'}).locator('tbody tr')).toHaveCount(1);
  await expect(buyer.getByRole('table',{name:'Order history'})).toContainText('filled');
  await buyer.getByRole('button',{name:'Trade history',exact:true}).click();
  await expect(buyer.getByRole('table',{name:'Trade history'}).locator('tbody tr')).toHaveCount(1);
  await expect(buyer.getByRole('table',{name:'Trade history'})).toContainText('buy');
  const artifacts=process.env.TEST_ARTIFACT_DIR || 'test-results';
  await buyer.screenshot({path:join(artifacts,'history-desktop.png'),fullPage:true});
  await buyer.setViewportSize({width:390,height:844});
  await expect.poll(()=>buyer.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await buyer.screenshot({path:join(artifacts,'history-mobile.png'),fullPage:true});
  // Stored candles load through the real history endpoint on a fresh page.
  const candles=buyer.waitForResponse(r=>r.url().includes('/api/v1/klines?') && r.ok());
  await buyer.reload();await candles;
  await expect(buyer.getByTestId('candle-count')).not.toHaveText('0 candles');
  let failCandles=true;
  await buyer.route('**/api/v1/klines?*',route=>failCandles ? route.abort('connectionrefused') : route.continue());
  await buyer.getByRole('button',{name:'1m',exact:true}).click();
  await expect(buyer.getByText('Historical candles unavailable;', {exact:false})).toBeVisible();
  await expect(buyer.getByRole('button',{name:'Buy SOL',exact:true})).toBeEnabled();
  failCandles=false;await buyer.getByRole('button',{name:'Retry history',exact:true}).click();
  await expect(buyer.getByText('Historical candles unavailable;', {exact:false})).toHaveCount(0);
  await expect(buyer.getByTestId('candle-count')).not.toHaveText('0 candles');
  await a.close();await b.close();
});
